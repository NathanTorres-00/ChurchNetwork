// Builds the deployable site into dist/: the root HTML pages plus assets/, review/ and versions/, with
// review/config.js pointing at the Convex deployment, convex/limits.js (only that file), which review/ imports
// for the limits it shares with the backend, and versions.json, the Versions panel's list of builds. Vercel runs it through `npx convex deploy --cmd ...`,
// which sets CONVEX_URL for the deployment it just pushed to.
import { cpSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildVersionList, fetchDeployments, readNotes } from './versions.js';

export const configSource = url => `// Generated by scripts/build-static.js or scripts/write-config.js. Do not edit.\nexport const CONVEX_URL = ${JSON.stringify(url)};\n`;

export function buildStatic({ root, out, convexUrl, versions = [], versionsAvailable = false }) {
  if (!convexUrl) throw new Error('CONVEX_URL is not set; run this through `npx convex deploy --cmd`.');
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  for (const name of readdirSync(root)) {
    if (name.endsWith('.html')) cpSync(join(root, name), join(out, name));
  }
  cpSync(join(root, 'assets'), join(out, 'assets'), { recursive: true });
  cpSync(join(root, 'review'), join(out, 'review'), { recursive: true });
  cpSync(join(root, 'versions'), join(out, 'versions'), { recursive: true });
  mkdirSync(join(out, 'convex'));
  cpSync(join(root, 'convex', 'limits.js'), join(out, 'convex', 'limits.js'));
  writeFileSync(join(out, 'review', 'config.js'), configSource(convexUrl));
  writeFileSync(join(out, 'versions.json'), JSON.stringify({ versions, available: versionsAvailable }));
}

// The builds Vercel has kept, plus the one being made (from Vercel's build environment). Without a token or an
// answer from the API the build goes on with just the current build, and the panel says history is unavailable.
async function loadVersions(root, env) {
  const notes = readNotes(join(root, 'versions.json'));
  const current = env.VERCEL_URL
    ? { url: env.VERCEL_URL, created: Date.now(), sha: env.VERCEL_GIT_COMMIT_SHA, message: env.VERCEL_GIT_COMMIT_MESSAGE }
    : null;
  try {
    const deployments = await fetchDeployments({ token: env.VERCEL_VERSIONS_TOKEN });
    return { versions: buildVersionList({ deployments, current, notes }), versionsAvailable: true };
  } catch (err) {
    console.log('Version history unavailable:', err.message);
    return { versions: buildVersionList({ deployments: [], current, notes }), versionsAvailable: false };
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  const versions = await loadVersions(root, process.env);
  buildStatic({ root, out: join(root, 'dist'), convexUrl: process.env.CONVEX_URL, ...versions });
  console.log('Built dist/ for', process.env.CONVEX_URL);
}
